def first_d_eigenvectors(matrix, d):
    eigenvalues, eigenvectors = np.linalg.eigh(matrix)

    # Sort the eigenvalues in descending order and get the indices
    sorted_indices = np.argsort(eigenvalues)[::-1]

    # Get the indices of the first d eigenvalues
    top_d_indices = sorted_indices[:d]

    # Get the corresponding eigenvectors to form the eigenmatrix
    first_d_vec = eigenvectors[:, top_d_indices]

    return first_d_vec

