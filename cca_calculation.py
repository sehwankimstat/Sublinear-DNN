## Network structure

class NN(nn.Module):
    def __init__(self, input_size, output_size, num_layers, hidden_units):
        super(NN, self).__init__()
        self.act=nn.Tanh()

        self.input_size = input_size
        self.output_size = output_size
        self.num_layers = num_layers
        self.hidden_units = hidden_units

        ### Define the input layer
        self.input_layer = nn.Linear(input_size, hidden_units)

        ## Define hidden layers (without Batch Norm)
        self.hidden_layers = nn.ModuleList([
            nn.Linear(hidden_units, hidden_units) for _ in range(num_layers - 1)
        ])

        # Define the output layer
        self.output_layer = nn.Linear(hidden_units, output_size)

    def forward(self, x):
        # Input layer
        x = self.act(self.input_layer(x))

        # Hidden layers
        for layer in self.hidden_layers:
            x = self.act(layer(x))

        # Output layer
        x = self.output_layer(x)

        return x

def custom_weight_init(m):
    if isinstance(m, nn.Linear):
        m.weight.data = 0.5*torch.tensor(np.random.choice([-2, -1, 0, 1, 2], size=m.weight.shape).astype(np.float32))
        m.bias.data = torch.normal(mean=0.0, std=0.02, size=m.bias.shape)


