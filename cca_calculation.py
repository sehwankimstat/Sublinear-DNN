def mean_se(x):
    x = np.asarray(x)
    return np.mean(x), np.std(x) / np.sqrt(len(x))


def format_mean_se(x, digits=3):
    m, se = mean_se(x)
    return f"{m:.{digits}f} ({se:.{digits}f})"



